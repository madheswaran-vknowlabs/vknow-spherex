interface IndividualPDFProps {
  user: any;
  summary: any;
  tasks: any[];
  weeklyUpdates: any[];
  periodLabel?: string;
}

const IndividualPDFDocument = ({
  user,
  summary,
  tasks,
  weeklyUpdates,
  periodLabel,
}: IndividualPDFProps) => (
  <Document>
    <Page size="A4" style={styles.page}>
      <View style={styles.headerStrip}>
        <Text style={styles.headerTitle}>VKNOW SPHEREX — INDIVIDUAL PERFORMANCE REPORT</Text>
        <Text style={styles.headerSubtitle}>
          Work Completion, Logged Engineering Hours &amp; Weekly Status History
        </Text>
      </View>

      <View style={styles.metaRow}>
        <Text>Member: {user.name}</Text>
        <Text>Department: {user.department || "Engineering"}</Text>
        <Text>Role: {user.role?.toUpperCase() || "TEAM MEMBER"}</Text>
        <Text>Period: {periodLabel || "All Time"}</Text>
      </View>

      {/* KPI Cards */}
      <Text style={styles.sectionTitle}>Performance Summary</Text>
      <View style={styles.kpiGrid}>
        <View style={styles.kpiCard}>
          <Text style={styles.kpiLabel}>Assigned Tasks</Text>
          <Text style={styles.kpiValue}>{tasks.length}</Text>
          <Text style={styles.kpiSub}>
            {tasks.filter((t) => t.status === "Completed").length} completed
          </Text>
        </View>

        <View style={styles.kpiCard}>
          <Text style={styles.kpiLabel}>Logged Hours</Text>
          <Text style={styles.kpiValue}>{summary.totalLoggedHours || 0} hrs</Text>
          <Text style={styles.kpiSub}>Est: {summary.totalEstimatedHours || 0} hrs</Text>
        </View>

        <View style={styles.kpiCard}>
          <Text style={styles.kpiLabel}>On-Time Delivery Rate</Text>
          <Text style={[styles.kpiValue, styles.badgeGreen]}>{summary.onTimeRate || 100}%</Text>
          <Text style={styles.kpiSub}>
            {tasks.filter((t) => t.lagInDays === 0).length} tasks on time
          </Text>
        </View>
      </View>

      {/* Assigned Tasks Table */}
      <Text style={styles.sectionTitle}>My Deliverables &amp; Status</Text>
      <View style={styles.table}>
        <View style={styles.tableHeader}>
          <Text style={[styles.tableHeaderCell, { width: "35%" }]}>Deliverable / Task</Text>
          <Text style={[styles.tableHeaderCell, { width: "20%" }]}>Project</Text>
          <Text style={[styles.tableHeaderCell, { width: "12%" }]}>Priority</Text>
          <Text style={[styles.tableHeaderCell, { width: "13%" }]}>Status</Text>
          <Text style={[styles.tableHeaderCell, { width: "10%" }]}>Est / Log</Text>
          <Text style={[styles.tableHeaderCell, { width: "10%" }]}>Lag</Text>
        </View>

        {tasks.map((t, idx) => (
          <View key={t._id} style={[styles.tableRow, idx % 2 === 1 ? styles.tableRowAlt : {}]}>
            <Text style={[styles.tableCell, { width: "35%" }]}>{t.title}</Text>
            <Text style={[styles.tableCell, { width: "20%" }]}>
              {t.projectId?.name || t.projectId?.code || "-"}
            </Text>
            <Text style={[styles.tableCell, { width: "12%" }]}>{t.priority || "Medium"}</Text>
            <Text style={[styles.tableCell, { width: "13%" }]}>{t.status}</Text>
            <Text style={[styles.tableCell, { width: "10%" }]}>
              {t.estimatedHours || 0}h / {t.loggedHours || 0}h
            </Text>
            <Text
              style={[
                styles.tableCell,
                { width: "10%" },
                t.lagInDays > 0 ? styles.badgeRed : styles.badgeGreen,
              ]}
            >
              {t.lagInDays > 0 ? `+${t.lagInDays}d` : "0d"}
            </Text>
          </View>
        ))}
      </View>

      {/* Weekly Updates History */}
      <Text style={styles.sectionTitle}>Weekly Updates History</Text>
      <View style={styles.table}>
        <View style={styles.tableHeader}>
          <Text style={[styles.tableHeaderCell, { width: "12%" }]}>Week #</Text>
          <Text style={[styles.tableHeaderCell, { width: "16%" }]}>Date</Text>
          <Text style={[styles.tableHeaderCell, { width: "12%" }]}>Hours</Text>
          <Text style={[styles.tableHeaderCell, { width: "30%" }]}>Deliverables Summary</Text>
          <Text style={[styles.tableHeaderCell, { width: "30%" }]}>Blockers</Text>
        </View>

        {weeklyUpdates.map((w, idx) => (
          <View key={w._id} style={[styles.tableRow, idx % 2 === 1 ? styles.tableRowAlt : {}]}>
            <Text style={[styles.tableCell, { width: "12%" }]}>Wk {w.weekNumber || "-"}</Text>
            <Text style={[styles.tableCell, { width: "16%" }]}>
              {w.weekStartDate ? format(new Date(w.weekStartDate), "dd MMM yyyy") : "-"}
            </Text>
            <Text style={[styles.tableCell, { width: "12%" }]}>{w.hoursSpent || 0} hrs</Text>
            <Text style={[styles.tableCell, { width: "30%" }]}>
              {w.summary?.length > 45 ? w.summary.slice(0, 42) + "..." : w.summary || "-"}
            </Text>
            <Text style={[styles.tableCell, { width: "30%" }]}>
              {w.blockers?.length > 45 ? w.blockers.slice(0, 42) + "..." : w.blockers || "None"}
            </Text>
          </View>
        ))}
      </View>

      <View style={styles.footer} fixed>
        <Text>VKnow SphereX Individual Tracking &bull; Confidential</Text>
        <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
      </View>
    </Page>
  </Document>
);

export async function generateConsolidatedPDF(data: ConsolidatedPDFProps): Promise<Buffer> {
  const buffer = await renderToBuffer(<ConsolidatedPDFDocument {...data} />);
  return Buffer.from(buffer);
}

export async function generateIndividualPDF(data: IndividualPDFProps): Promise<Buffer> {
  const buffer = await renderToBuffer(<IndividualPDFDocument {...data} />);
  return Buffer.from(buffer);
}
